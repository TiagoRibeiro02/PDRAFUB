const hre = require("hardhat");
const { ethers } = hre;
const fs = require("fs");
const path = require("path");
const solc = require("solc");

function buildCompilerInput(sources, { viaIR = false, optimizerEnabled = true } = {}) {
  return {
    language: "Solidity",
    sources: Object.fromEntries(
      Object.entries(sources).map(([file, content]) => [file, { content }])
    ),
    settings: {
      optimizer: { enabled: optimizerEnabled, runs: 200 },
      viaIR,
      outputSelection: {
        "*": {
          "*": ["abi", "evm.bytecode.object"],
        },
      },
    },
  };
}

function extractCompiledArtifact(output, contractFile, contractName) {
  if (output.errors) {
    const errors = output.errors.filter((e) => e.severity === "error");
    if (errors.length > 0) {
      throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
    }
  }

  const artifact = output.contracts?.[contractFile]?.[contractName];
  if (!artifact) {
    throw new Error(`Could not compile ${contractName} from ${contractFile}`);
  }

  return {
    abi: artifact.abi,
    bytecode: `0x${artifact.evm.bytecode.object}`,
  };
}

function compileFromSources(sources, contractFile, contractName, options = {}) {
  const input = buildCompilerInput(sources, options);
  const output = JSON.parse(solc.compile(JSON.stringify(input)));
  return extractCompiledArtifact(output, contractFile, contractName);
}

async function loadSolcVersion(versionTag) {
  return new Promise((resolve, reject) => {
    solc.loadRemoteVersion(versionTag, (err, specificSolc) => {
      if (err) {
        reject(
          new Error(
            `Failed to load Solidity compiler ${versionTag}. HALO2 verifier requires exact compiler version. Original error: ${err.message || err}`
          )
        );
        return;
      }
      resolve(specificSolc);
    });
  });
}

async function compileFromSourcesWithVersion(
  sources,
  contractFile,
  contractName,
  versionTag,
  options = {}
) {
  const specificSolc = await loadSolcVersion(versionTag);
  const input = buildCompilerInput(sources, options);
  const output = JSON.parse(specificSolc.compile(JSON.stringify(input)));
  return extractCompiledArtifact(output, contractFile, contractName);
}

function normalizeSolidityPragma(source) {
  // Optional fallback when exact compiler is unavailable.
  return source.replace(
    /pragma\s+solidity\s+0\.8\.(\d+)\s*;/,
    (_, patch) => `pragma solidity >=0.8.${patch} <0.9.0;`
  );
}

async function deployFromCompiled(artifact, signer, args = []) {
  const factory = new ethers.ContractFactory(artifact.abi, artifact.bytecode, signer);
  const contract = await factory.deploy(...args);
  await contract.waitForDeployment();
  return contract;
}

async function getCappedGasLimit(provider, estimatedGas) {
  const latestBlock = await provider.getBlock("latest");
  const blockGasLimit = latestBlock?.gasLimit ?? 30_000_000n;

  // Add a safety margin to estimate but stay under current block gas limit.
  const withBuffer = (estimatedGas * 120n) / 100n;
  const cap = (blockGasLimit * 95n) / 100n;

  return withBuffer < cap ? withBuffer : cap;
}

async function getNetworkTxGasLimit(provider, ratioPercent = 80n) {
  const latestBlock = await provider.getBlock("latest");
  const blockGasLimit = latestBlock?.gasLimit ?? 30_000_000n;
  const ratioGasLimit = (blockGasLimit * ratioPercent) / 100n;
  const safeCap = (blockGasLimit * 95n) / 100n;
  let gasLimit = ratioGasLimit > safeCap ? safeCap : ratioGasLimit;

  // Hardhat/localhost EDR enforces tx.gas <= 16,777,216 (2^24).
  if (hre.network.name === "hardhat" || hre.network.name === "localhost") {
    const hardhatTxCap = 16_777_215n;
    gasLimit = gasLimit > hardhatTxCap ? hardhatTxCap : gasLimit;
  }

  return gasLimit;
}

function getHalo2AdapterSource() {
  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.19;

contract Halo2VerifierAdapter {
    address public verifier;

    constructor(address _verifier) {
        verifier = _verifier;
    }

    function verifyProof(bytes memory proof, uint[] memory pubSignals)
        public
        returns (bool)
    {
      require(pubSignals.length == 5, "Invalid number of public signals");
      // The proof argument is the full verifier calldata generated by snark-verifier-sdk.
      // Use an external call so verifier runtime assumptions (memory layout) stay intact.
      (bool ok, ) = verifier.call(proof);
        return ok;
    }

    function verifyProofTx(bytes memory proof, uint[] memory pubSignals)
        external
        returns (bool)
    {
        bool valid = verifyProof(proof, pubSignals);
        require(valid, "Invalid HALO2 proof");
        return true;
    }

    function getVerifierAddress() external view returns (address) {
        return verifier;
    }
}
`;
}

function getHalo2KycSource() {
  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.19;

interface IHalo2VerifierAdapter {
  function verifyProofTx(bytes memory proof, uint[] memory pubSignals) external returns (bool);
}

contract Halo2KYCCompliance {
  address public verifier;

  struct ComplianceData {
    string did;
    string commitment;
    string issuerDID;
    uint256 expiryDate;
    bool revoked;
  }

  mapping(string => ComplianceData) public records;

  constructor(address _verifier) {
    verifier = _verifier;
  }

  function submitComplianceProof(
    string memory did,
    string memory commitment,
    string memory issuerDID,
    uint256 expiryDate,
    bytes32,
    bool,
    bytes memory proof,
    uint[] memory pubSignals
  ) external {
    require(pubSignals.length == 5, "Invalid number of public signals");
    require(bytes(did).length > 0, "DID cannot be empty");
    require(bytes(issuerDID).length > 0, "Issuer cannot be empty");
    require(_parseDecimal(did) == pubSignals[0], "DID does not match proof");
    require(pubSignals[1] == 1, "Proof status must be compliant");
    require(_parseDecimal(commitment) == pubSignals[2], "Commitment does not match proof");
    require(_parseDecimal(issuerDID) == pubSignals[3], "Issuer does not match proof");
    require(expiryDate == pubSignals[4], "Expiry does not match proof");
    bool ok = IHalo2VerifierAdapter(verifier).verifyProofTx(proof, pubSignals);
    require(ok, "Invalid HALO2 proof");

    records[did] = ComplianceData({
      did: did,
      commitment: commitment,
      issuerDID: issuerDID,
      expiryDate: expiryDate,
      revoked: false
    });
  }

  function _parseDecimal(string memory value) private pure returns (uint256 result) {
    bytes memory data = bytes(value);
    require(data.length > 0, "Numeric value cannot be empty");

    for (uint256 i = 0; i < data.length; i++) {
      require(data[i] >= 0x30 && data[i] <= 0x39, "Value must be decimal");
      result = result * 10 + uint256(uint8(data[i]) - 0x30);
    }
  }
}
`;
}

async function main() {
  const root = path.resolve(__dirname, "../../");
  const perfRoot = path.join(root, "performance-experiments");
  const halo2ArtifactPath = path.join(
    perfRoot,
    "halo2",
    "artifacts",
    "halo2-evm-bench.json"
  );

  if (!fs.existsSync(halo2ArtifactPath)) {
    throw new Error(
      `Missing HALO2 artifact JSON at ${halo2ArtifactPath}. Run cargo run --release --bin halo2_evm_gas -- --bench-json in performance-experiments/halo2/circuit first.`
    );
  }

  const halo2Artifacts = JSON.parse(fs.readFileSync(halo2ArtifactPath, "utf8"));
  const verifierSolPath = halo2Artifacts.verifierSolidityPath;

  if (!verifierSolPath || !fs.existsSync(verifierSolPath)) {
    throw new Error(`Missing verifier solidity source: ${verifierSolPath}`);
  }

  const verifierSource = fs.readFileSync(verifierSolPath, "utf8");
  const verifierArtifact = await compileFromSourcesWithVersion(
    { "Halo2Verifier.sol": verifierSource },
    "Halo2Verifier.sol",
    "Halo2Verifier",
    "v0.8.19+commit.7dd6d404",
    { viaIR: false, optimizerEnabled: false }
  );

  const kycArtifact = compileFromSources(
    { "Halo2KYCCompliance.sol": getHalo2KycSource() },
    "Halo2KYCCompliance.sol",
    "Halo2KYCCompliance",
    { viaIR: false }
  );

  const adapterArtifact = compileFromSources(
    { "Halo2VerifierAdapter.sol": getHalo2AdapterSource() },
    "Halo2VerifierAdapter.sol",
    "Halo2VerifierAdapter",
    { viaIR: false }
  );

  const [signer] = await ethers.getSigners();

  const verifier = await deployFromCompiled(verifierArtifact, signer);
  const verifierAddress = await verifier.getAddress();
  const adapter = await deployFromCompiled(adapterArtifact, signer, [verifierAddress]);
  const adapterAddress = await adapter.getAddress();
  const kyc = await deployFromCompiled(kycArtifact, signer, [adapterAddress]);

  const proofCandidates = [halo2Artifacts.calldataHex, halo2Artifacts.proofHex]
    .filter((p) => typeof p === "string" && p.length > 2)
    .filter((p, i, arr) => arr.indexOf(p) === i);

  if (proofCandidates.length === 0) {
    throw new Error("Missing calldataHex/proofHex in halo2 artifact JSON");
  }
  const publicSignals = halo2Artifacts.publicSignals.map((x) => x.toString());

  const verifyGasLimit = await getNetworkTxGasLimit(ethers.provider, 80n);

  let selectedProofHex = null;
  let rcVerify = null;
  let verifyProofTxMs = null;
  let lastVerifyError = null;

  for (const candidate of proofCandidates) {
    try {
      const verifyStart = process.hrtime.bigint();
      const txVerify = await adapter.verifyProofTx(candidate, publicSignals, {
        gasLimit: verifyGasLimit,
      });
      rcVerify = await txVerify.wait();
      const verifyEnd = process.hrtime.bigint();
      verifyProofTxMs = Number(((Number(verifyEnd - verifyStart) / 1_000_000)).toFixed(2));
      selectedProofHex = candidate;
      break;
    } catch (error) {
      lastVerifyError = error;
    }
  }

  if (!selectedProofHex || !rcVerify) {
    throw new Error(
      `All verifier payload attempts failed. Last error: ${lastVerifyError?.message || lastVerifyError}`
    );
  }

  const did = publicSignals[0].toString();
  const commitment = publicSignals[2].toString();
  const issuerDid = publicSignals[3].toString();
  const expiryDate = BigInt(publicSignals[4]);

  const kycGasLimit = await getNetworkTxGasLimit(ethers.provider, 85n);

  const txKyc = await kyc.submitComplianceProof(
    did,
    commitment,
    issuerDid,
    expiryDate,
    ethers.ZeroHash,
    false,
    selectedProofHex,
    publicSignals,
    { gasLimit: kycGasLimit }
  );
  const rcKyc = await txKyc.wait();

  const output = {
    protocol: "HALO2",
    adapter: adapterAddress,
    verifier: verifierAddress,
    kyc: await kyc.getAddress(),
    payloadFormat:
      selectedProofHex === halo2Artifacts.calldataHex ? "calldataHex" : "proofHex",
    verifyProofTxGas: rcVerify.gasUsed.toString(),
    submitComplianceProofGas: rcKyc.gasUsed.toString(),
    verifierSource: verifierSolPath,
  };

  const timingOutput = {
    protocol: "HALO2",
    verificationMs: verifyProofTxMs,
  };

  console.log("=== HALO2 ON-CHAIN GAS BENCHMARK ===");
  console.log(JSON.stringify(output, null, 2));
  console.log(`BENCHMARK_HALO2_GAS_JSON=${JSON.stringify(output)}`);
  console.log(`BENCHMARK_HALO2_VERIFICATION_TIME_JSON=${JSON.stringify(timingOutput)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
